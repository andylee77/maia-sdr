const TWO56_OVER_TWO_PI: f32 = 256.0 / TWO_PI;
const AUDIO_SCALAR: f32 = 1.0 / 32767.0;
const MAX_AUDIO_AMPLITUDE: f32 = 0.95;
const WHITE_NOISE_SCALAR: f32 = TWO_PI / 53125.0;
const UNVOICED_SCALING_COEFFICIENT: f32 = 146.17696;

/// The public IMBE decoder. Maintains inter-frame state.
pub struct ImbeDecoder {
    previous_params: ModelParameters,
    previous_phase_o: [f32; 57],
    previous_phase_v: [f32; 57],
    previous_uw: [f32; 256],
    noise_gen: MbeNoiseGenerator,
    white_noise_gen: WhiteNoiseGenerator,
}

impl ImbeDecoder {
    pub fn new() -> Self {
        Self {
            previous_params: ModelParameters::new_default(),
            previous_phase_o: [0.0; 57],
            previous_phase_v: [0.0; 57],
            previous_uw: [0.0; 256],
            noise_gen: MbeNoiseGenerator::new(),
            white_noise_gen: WhiteNoiseGenerator::new(),
        }
    }

    /// Decode one IMBE frame (18 bytes / 144 bits) into 160 f32 audio samples.
    /// Samples are in range approximately -1.0 to 1.0.
    pub fn decode_frame(&mut self, frame_bytes: &[u8; 18]) -> [f32; 160] {
        let params = decode_frame(frame_bytes, &self.previous_params);

        let audio = if params.is_max_frame_repeat() || params.requires_muting() {
            let samples = self.white_noise_gen.get_samples(160, 0.003);
            let mut out = [0.0f32; 160];
            out.copy_from_slice(&samples);
            out
        } else {
            self.synthesize_voice(&params)
        };

        self.previous_params = params;
        audio
    }

    fn synthesize_voice(&mut self, params: &ModelParameters) -> [f32; 160] {
        // Alg #117 - noise sequence
        let u = self.noise_gen.next_buffer();

        let unvoiced = self.get_unvoiced(params, &u);
        let voiced = self.get_voiced(params, &u);

        let mut audio = [0.0f32; 160];
        for x in 0..160 {
            audio[x] = clip((voiced[x] + unvoiced[x]) * AUDIO_SCALAR);
        }
        audio
    }

    fn get_unvoiced(&mut self, params: &ModelParameters, white_noise: &[f32; 256]) -> [f32; 160] {
        // Apply synthesis window
        let mut uw = [0.0f32; 256];
        for x in 0..256 {
            uw[x] = white_noise[x] * synthesis_window(x as i32 - 128);
        }

        // Frequency band edges
        let l = params.l;
        let multiplier = TWO56_OVER_TWO_PI * params.w0;

        let mut a_min = vec![0i32; l + 1];
        let mut b_max = vec![0i32; l + 1];
        for li in 1..=l {
            a_min[li] = ((li as f32 - 0.5) * multiplier).ceil() as i32;
            b_max[li] = ((li as f32 + 0.5) * multiplier).ceil() as i32;
        }

        // Forward DFT
        let mut uw_arr = [0.0f32; 256];
        uw_arr.copy_from_slice(&uw);
        let mut uw_freq = real_dft_forward_256(&uw_arr);

        // Alg 120 - band-level scaling
        let mut dft_bin_scalar = [0.0f32; 128];
        let voicing = &params.voicing;
        let m_enhanced = &params.enhanced_spectral;

        for li in 1..=l {
            if li < voicing.len() && !voicing[li] {
                let mut numerator = 0.0f32;
                let amin = a_min[li].max(0) as usize;
                let bmax = (b_max[li].max(0) as usize).min(128);

                for n in amin..bmax {
                    if n < 128 {
                        let dft_idx = 2 * n;
                        numerator += uw_freq[dft_idx] * uw_freq[dft_idx];
                        numerator += uw_freq[dft_idx + 1] * uw_freq[dft_idx + 1];
                    }
                }

                let denom = (bmax as f32 - amin as f32).max(1.0);
                let ml = if li < m_enhanced.len() { m_enhanced[li] } else { 0.0 };
                let scalar = UNVOICED_SCALING_COEFFICIENT * ml / (numerator / denom).sqrt();

                for n in amin..bmax {
                    if n < 128 {
                        dft_bin_scalar[n] = scalar;
                    }
                }
            }
        }

        // Apply scaling
        for bin in 0..128 {
            let idx = 2 * bin;
            uw_freq[idx] *= dft_bin_scalar[bin];
            uw_freq[idx + 1] *= dft_bin_scalar[bin];
        }

        // Inverse DFT
        let uw_time = real_dft_inverse_256(&uw_freq);

        // Alg #126 - weighted overlap add
        let mut unvoiced = [0.0f32; 160];
        for n in 0..160 {
            let prev_win = synthesis_window(n as i32);
            let curr_win = synthesis_window(n as i32 - SAMPLES_PER_FRAME as i32);

            let prev_uw = if n < 128 { self.previous_uw[n + 128] } else { 0.0 };
            let curr_uw = if n >= 32 { uw_time[n - 32] } else { 0.0 };

            let denom = prev_win * prev_win + curr_win * curr_win;
            if denom > 0.0 {
                unvoiced[n] = (prev_win * prev_uw + curr_win * curr_uw) / denom;
            }
        }

        self.previous_uw = uw_time;
        unvoiced
    }

    fn get_voiced(&mut self, current: &ModelParameters, u: &[f32; 256]) -> [f32; 160] {
        let current_freq = current.w0;
        let previous_freq = self.previous_params.w0;
        let average_freq = (previous_freq + current_freq) / 2.0;
        let phase_offset = average_freq * SAMPLES_PER_FRAME as f32;

        // Alg #139
        let mut current_phase_v = [0.0f32; 57];
        for li in 1..=56 {
            self.previous_phase_v[li] %= TWO_PI;
            current_phase_v[li] = self.previous_phase_v[li] + phase_offset * li as f32;
        }

        // Short circuit if no voiced bands in either frame
        if !self.previous_params.has_voiced_bands() && !current.has_voiced_bands() {
            self.previous_phase_v = current_phase_v;
            return [0.0; 160];
        }

        let current_l = current.l;
        let previous_l = self.previous_params.l;
        let max_l = current_l.max(previous_l);

        // Resize voicing to max_l + 1
        let mut current_voicing = current.voicing.clone();
        current_voicing.resize(max_l + 1, false);
        let mut previous_voicing = self.previous_params.voicing.clone();
        previous_voicing.resize(max_l + 1, false);

        // Alg #140
        let unvoiced_count = current.unvoiced_band_count();
        let mut current_phase_o = [0.0f32; 57];
        let threshold = (current_l as f32 / 4.0).floor() as usize;

        for li in 1..=56 {
            if li <= threshold {
                current_phase_o[li] = current_phase_v[li];
            } else if li <= max_l {
                let pl = WHITE_NOISE_SCALAR * u[li] - PI;
                current_phase_o[li] = current_phase_v[li] + (unvoiced_count as f32 * pl) / current_l as f32;
            }
        }

        let current_m = &current.enhanced_spectral;
        let previous_m = &self.previous_params.enhanced_spectral;
        let mut voiced = [0.0f32; 160];

        let exceeds_threshold = (current_freq - previous_freq).abs() >= 0.1 * current_freq;

        for n in 0..SAMPLES_PER_FRAME {
            for li in 1..=max_l {
                let cv = current_voicing[li];
                let pv = previous_voicing[li];

                let cm = if li < current_m.len() { current_m[li] } else { 0.0 };
                let pm = if li < previous_m.len() { previous_m[li] } else { 0.0 };

                if cv && pv {
                    if li >= 8 || exceeds_threshold {
                        // Alg #133
                        let prev_phase = self.previous_phase_o[li] + previous_freq * n as f32 * li as f32;
                        voiced[n] += 2.0 * synthesis_window(n as i32) * pm * prev_phase.cos();

                        let curr_phase = current_phase_o[li] + current_freq * (n as i32 - SAMPLES_PER_FRAME as i32) as f32 * li as f32;
                        voiced[n] += 2.0 * synthesis_window(n as i32 - SAMPLES_PER_FRAME as i32) * cm * curr_phase.cos();
                    } else {
                        // Alg #135 - amplitude interpolation
                        let amplitude = pm + (n as f32 / SAMPLES_PER_FRAME as f32) * (cm - pm);

                        // Alg #137
                        let ol = current_phase_o[li] - self.previous_phase_o[li] - phase_offset * li as f32;

                        // Alg #138
                        let wl = (ol - TWO_PI * ((ol + PI) / TWO_PI).floor()) / 160.0;

                        // Alg #136
                        let phase = self.previous_phase_o[li]
                            + ((previous_freq * li as f32) + wl) * n as f32
                            + (current_freq - previous_freq) * (li as f32 * (n as f32).powi(2)) / 320.0;

                        // Alg #134
                        voiced[n] += 2.0 * amplitude * phase.cos();
                    }
                } else if !cv && pv {
                    // Alg #131
                    let phase = self.previous_phase_o[li] + previous_freq * n as f32 * li as f32;
                    voiced[n] += 2.0 * synthesis_window(n as i32) * pm * phase.cos();
                } else if cv && !pv {
                    // Alg #132
                    let phase = current_phase_o[li] + current_freq * (n as i32 - SAMPLES_PER_FRAME as i32) as f32 * li as f32;
                    voiced[n] += 2.0 * synthesis_window(n as i32 - SAMPLES_PER_FRAME as i32) * cm * phase.cos();
                }
                // Both unvoiced: contribute nothing (Alg #130)
            }
        }

        self.previous_phase_v = current_phase_v;
        self.previous_phase_o = current_phase_o;

        voiced
    }
}

fn clip(value: f32) -> f32 {
    if value > MAX_AUDIO_AMPLITUDE {
        MAX_AUDIO_AMPLITUDE
    } else if value < -MAX_AUDIO_AMPLITUDE {
        -MAX_AUDIO_AMPLITUDE
    } else {
        value
    }
}


struct MbeNoiseGenerator {
    sample: f32,
    current_buffer: [f32; 256],
}

impl MbeNoiseGenerator {
    fn new() -> Self {
        let mut gen = Self {
            sample: 3147.0,
            current_buffer: [0.0; 256],
        };
        // Initialize buffer
        for x in 0..256 {
            gen.current_buffer[x] = gen.next_sample();
        }
        gen
    }

    fn next_sample(&mut self) -> f32 {
        let next = self.sample;
        self.sample = (171.0 * self.sample + 11213.0) % 53125.0;
        next
    }

    fn next_buffer(&mut self) -> [f32; 256] {
        let copy = self.current_buffer;
        // Shift last 96 samples to beginning
        self.current_buffer.copy_within(160..256, 0);
        for x in 96..256 {
            self.current_buffer[x] = self.next_sample();
        }
        copy
    }
}

struct WhiteNoiseGenerator {
    // Simple PRNG instead of java.util.Random
    state: u32,
    current_buffer: [f32; 256],
}

const WHITE_NOISE_GAIN: f32 = 26562.5;

impl WhiteNoiseGenerator {
    fn new() -> Self {
        let mut gen = Self {
            state: 12345,
            current_buffer: [0.0; 256],
        };
        gen.next_random(); // warm up
        for x in 0..256 {
            gen.current_buffer[x] = gen.next_random() * WHITE_NOISE_GAIN;
        }
        gen
    }

    /// Simple xorshift32 PRNG producing values in -1.0..1.0
    fn next_random(&mut self) -> f32 {
        self.state ^= self.state << 13;
        self.state ^= self.state >> 17;
        self.state ^= self.state << 5;
        // Map to -1.0..1.0
        (self.state as f32 / u32::MAX as f32) * 2.0 - 1.0
    }

    fn next_buffer(&mut self) -> [f32; 256] {
        let copy = self.current_buffer;
        self.current_buffer.copy_within(160..256, 0);
        for x in 96..256 {
            self.current_buffer[x] = self.next_random() * WHITE_NOISE_GAIN;
        }
        copy
    }

    fn get_samples(&mut self, length: usize, gain: f32) -> Vec<f32> {
        let mut samples = vec![0.0f32; length];
        for s in samples.iter_mut() {
            *s = self.next_random() * gain;
        }
        samples
    }
}

// ============================================================================
// Simple 256-point real DFT (forward and inverse)
// ============================================================================

/// 256-point real forward DFT. Input: 256 real samples. Output: packed format
/// compatible with JTransforms realForward: [Re(0), Re(128), Re(1), Im(1), Re(2), Im(2), ... Re(127), Im(127)]
fn real_dft_forward_256(input: &[f32; 256]) -> [f32; 256] {
    let n = 256;
    let mut output = [0.0f32; 256];

    // DC component (bin 0)
    let mut re0: f32 = 0.0;
    for k in 0..n {
        re0 += input[k];
    }
    output[0] = re0;

    // Nyquist component (bin 128)
    let mut re128: f32 = 0.0;
    for k in 0..n {
        re128 += input[k] * if k % 2 == 0 { 1.0 } else { -1.0 };
    }
    output[1] = re128;

    // Bins 1..127
    for bin in 1..128 {
        let mut re: f32 = 0.0;
        let mut im: f32 = 0.0;
        for k in 0..n {
            let angle = TWO_PI * bin as f32 * k as f32 / n as f32;
            re += input[k] * angle.cos();
            im -= input[k] * angle.sin();
        }
        output[2 * bin] = re;
        output[2 * bin + 1] = im;
    }

    output
}

/// 256-point real inverse DFT (with scaling). Input/output in JTransforms packed format.
fn real_dft_inverse_256(freq: &[f32; 256]) -> [f32; 256] {
    let n = 256;
    let mut output = [0.0f32; 256];

    let re0 = freq[0];
    let re128 = freq[1];

    for k in 0..n {
        let mut sum = re0;
        sum += re128 * if k % 2 == 0 { 1.0 } else { -1.0 };

        for bin in 1..128 {
            let re = freq[2 * bin];
            let im = freq[2 * bin + 1];
            let angle = TWO_PI * bin as f32 * k as f32 / n as f32;
            sum += 2.0 * (re * angle.cos() - im * angle.sin());
        }

        output[k] = sum / n as f32;
    }

    output
}


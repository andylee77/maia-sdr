const HAMMING15_CHECKSUMS: [u32; 11] = [0xF, 0xE, 0xD, 0xC, 0xB, 0xA, 0x9, 0x7, 0x6, 0x5, 0x3];

fn hamming15_check_and_correct(frame: &mut [bool; 144], start_index: usize) -> u32 {
    let syndrome = hamming15_get_syndrome(frame, start_index);
    match syndrome {
        0 => 0,
        1 => {
            flip_bit(frame, start_index + 14);
            1
        }
        2 => {
            flip_bit(frame, start_index + 13);
            1
        }
        3 => {
            flip_bit(frame, start_index + 10);
            1
        }
        4 => {
            flip_bit(frame, start_index + 12);
            1
        }
        5 => {
            flip_bit(frame, start_index + 9);
            1
        }
        6 => {
            flip_bit(frame, start_index + 8);
            1
        }
        7 => {
            flip_bit(frame, start_index + 7);
            1
        }
        8 => {
            flip_bit(frame, start_index + 11);
            1
        }
        9 => {
            flip_bit(frame, start_index + 6);
            1
        }
        10 => {
            flip_bit(frame, start_index + 5);
            1
        }
        11 => {
            flip_bit(frame, start_index + 4);
            1
        }
        12 => {
            flip_bit(frame, start_index + 3);
            1
        }
        13 => {
            flip_bit(frame, start_index + 2);
            1
        }
        14 => {
            flip_bit(frame, start_index + 1);
            1
        }
        15 => {
            flip_bit(frame, start_index);
            1
        }
        _ => 2,
    }
}

fn hamming15_get_syndrome(frame: &[bool; 144], start_index: usize) -> u32 {
    let mut calculated = 0u32;
    for i in start_index..start_index + 11 {
        if frame[i] {
            calculated ^= HAMMING15_CHECKSUMS[i - start_index];
        }
    }
    let checksum = get_int_range(frame, start_index + 11, start_index + 14);
    checksum ^ calculated
}


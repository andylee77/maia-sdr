fn deinterleave(frame: &mut [bool; 144]) {
    let original = *frame;
    *frame = [false; 144];
    for i in 0..144 {
        if original[i] {
            frame[DEINTERLEAVE[i]] = true;
        }
    }
}

// ============================================================================
// BinaryFrame helpers -- operate on bool slices

/// Read an integer from non-contiguous bit positions (MSB-first).
fn get_int_indexed(frame: &[bool; 144], indexes: &[usize]) -> u32 {
    let mut value: u32 = 0;
    for &idx in indexes {
        value = (value << 1) | (frame[idx] as u32);
    }
    value
}

/// Read an integer from contiguous bits [start..=end] (MSB-first).
fn get_int_range(bits: &[bool], start: usize, end: usize) -> u32 {
    let mut value: u32 = 0;
    for x in start..=end {
        value = (value << 1) | (bits[x] as u32);
    }
    value
}

/// Load a value into contiguous bit positions [offset..offset+width) MSB-first.
fn load_bits(bits: &mut [bool], offset: usize, width: usize, value: u32) {
    for x in 0..width {
        let mask = 1u32 << (width - x - 1);
        bits[offset + x] = (value & mask) != 0;
    }
}

/// Flip a bit.
fn flip_bit(bits: &mut [bool], index: usize) {
    bits[index] = !bits[index];
}

/// Count set bits in a u32.
fn bit_count(v: u32) -> u32 {
    v.count_ones()
}

// ============================================================================
// Golay(23,12) error detection/correction
// ============================================================================

const GOLAY23_CHECKSUMS: [u32; 23] = [
    0x63A, 0x31D, 0x7B4, 0x3DA, 0x1ED, 0x6CC, 0x366, 0x1B3, 0x6E3, 0x54B, 0x49F, 0x475, 0x400,
    0x200, 0x100, 0x080, 0x040, 0x020, 0x010, 0x008, 0x004, 0x002, 0x001,
];

fn golay23_calculate_checksum(bits: &[bool], start: usize) -> u32 {
    let mut calculated = 0u32;
    for i in start..start + 12 {
        if bits[i] {
            calculated ^= GOLAY23_CHECKSUMS[i - start];
        }
    }
    calculated
}

fn golay23_get_syndrome(bits: &[bool], start: usize) -> u32 {
    let calculated = golay23_calculate_checksum(bits, start);
    let checksum = get_int_range(bits, start + 12, start + 22);
    checksum ^ calculated
}

/// Rotate left: shift bits[start..=end] left by 1, wrapping MSB to LSB.
fn rotate_left(bits: &mut Vec<bool>, start: usize, end: usize) {
    let wrap = bits[start];
    for x in start..end {
        bits[x] = bits[x + 1];
    }
    bits[end] = wrap;
}

/// Rotate right: shift bits[start..=end] right by n, wrapping LSB to MSB.
fn rotate_right(bits: &mut Vec<bool>, places: usize, start: usize, end: usize) {
    for _ in 0..places {
        let wrap = bits[end];
        for x in (start..end).rev() {
            bits[x + 1] = bits[x];
        }
        bits[start] = wrap;
    }
}

/// XOR value (of given width) into bits starting at offset.
fn xor_bits(bits: &mut Vec<bool>, offset: usize, width: usize, value: u32) {
    for x in 0..width {
        let mask = 1u32 << (width - x - 1);
        if (value & mask) != 0 {
            bits[offset + x] = !bits[offset + x];
        }
    }
}

fn golay23_check_and_correct(frame: &mut [bool; 144], start_index: usize) -> u32 {
    let syndrome = golay23_get_syndrome(frame, start_index);
    if syndrome == 0 {
        return 0;
    }

    // Make a working copy of the 23 bits
    let mut copy: Vec<bool> = frame[start_index..start_index + 23].to_vec();

    let mut index: i32 = -1;
    let mut syndrome_weight: u32 = 3;

    while index < 23 {
        if index != -1 {
            // Restore previous flipped bit
            if index > 0 {
                copy[(index - 1) as usize] = !copy[(index - 1) as usize];
            }
            copy[index as usize] = !copy[index as usize];
            syndrome_weight = 2;
        }

        let mut syndrome = golay23_get_syndrome_vec(&copy, 0);

        if syndrome > 0 {
            for i in 0..23 {
                let errors = bit_count(syndrome);
                if errors <= syndrome_weight {
                    xor_bits(&mut copy, 12, 11, syndrome);
                    rotate_right(&mut copy, i, 0, 22);

                    let mut total_errors = errors;
                    if index >= 0 {
                        total_errors += 1;
                    }

                    let corrected = get_int_range_vec(&copy, 0, 22);
                    let original = get_int_range(frame, start_index, start_index + 22);
                    let error_count = bit_count(original ^ corrected);

                    if error_count <= 3 {
                        load_bits(frame, start_index, 23, corrected);
                    }

                    return error_count;
                } else {
                    rotate_left(&mut copy, 0, 22);
                    syndrome = golay23_get_syndrome_vec(&copy, 0);
                }
            }
            index += 1;
        } else {
            // syndrome == 0 after flipping, means index bit was the only error
            index += 1;
        }
    }

    4 // uncorrectable
}

fn golay23_get_syndrome_vec(bits: &[bool], start: usize) -> u32 {
    let mut calculated = 0u32;
    for i in start..start + 12 {
        if bits[i] {
            calculated ^= GOLAY23_CHECKSUMS[i - start];
        }
    }
    let checksum = get_int_range_vec(bits, start + 12, start + 22);
    checksum ^ calculated
}

fn get_int_range_vec(bits: &[bool], start: usize, end: usize) -> u32 {
    let mut value: u32 = 0;
    for x in start..=end {
        value = (value << 1) | (bits[x] as u32);
    }
    value
}


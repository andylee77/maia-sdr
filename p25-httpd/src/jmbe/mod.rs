#[derive(Clone)]
struct ModelParameters {
    fund_index: Option<u32>, // None = INVALID
    w0: f32,
    l: usize,
    voicing: Vec<bool>,           // [L+1], index 0 unused
    log2_spectral: Vec<f32>,      // [L+1]
    spectral: Vec<f32>,           // [L+1]
    enhanced_spectral: Vec<f32>,  // [L+1]
    local_energy: f32,
    amplitude_threshold: i32,
    error_rate: f32,
    error_count_total: u32,
    error_count_coset0: u32,
    error_count4: u32,
    repeat_count: u32,
}

impl ModelParameters {
    fn new_default() -> Self {
        let (w0, l) = compute_fundamental(DEFAULT_FUND_INDEX);
        let lp1 = l + 1;
        Self {
            fund_index: Some(DEFAULT_FUND_INDEX),
            w0,
            l,
            voicing: vec![false; lp1],
            log2_spectral: vec![0.0; lp1],
            spectral: vec![1.0; lp1],
            enhanced_spectral: vec![1.0; lp1],
            local_energy: 75000.0,
            amplitude_threshold: 20480,
            error_rate: 0.0,
            error_count_total: 0,
            error_count_coset0: 0,
            error_count4: 0,
            repeat_count: 0,
        }
    }

    fn requires_muting(&self) -> bool {
        self.error_rate > 0.0875
    }

    fn is_max_frame_repeat(&self) -> bool {
        self.repeat_count >= 4
    }

    fn has_voiced_bands(&self) -> bool {
        self.voicing.iter().any(|&v| v)
    }

    fn unvoiced_band_count(&self) -> usize {
        self.voicing.iter().filter(|&&v| !v).count()
    }

    fn repeat_required(&self) -> bool {
        self.fund_index.is_none() || self.exceeds_error_threshold()
    }

    fn exceeds_error_threshold(&self) -> bool {
        self.error_count_coset0 >= 2
            && self.error_count_total as f32 >= (10.0 + 40.0 * self.error_rate)
    }

    fn requires_adaptive_smoothing(&self) -> bool {
        self.error_rate > 0.0125 || self.error_count_total > 4
    }
}


const PI_96: f32 = 0.96 * PI;

fn enhance_spectral_amplitudes(params: &mut ModelParameters, prev_local_energy: f32, prev_amp_threshold: i32) {
    let l = params.l;
    if l == 0 {
        return;
    }

    // Alg #105, #106
    let mut rm0: f32 = 0.0;
    let mut rm1: f32 = 0.0;
    for li in 1..=l {
        let a2 = params.spectral[li] * params.spectral[li];
        rm0 += a2;
        rm1 += a2 * (params.w0 * li as f32).cos();
    }

    if rm0 == 0.0 {
        params.enhanced_spectral = vec![0.0; l + 1];
        return;
    }

    let rm0sq = rm0 * rm0;
    let rm1sq = rm1 * rm1;

    // Alg #107 - enhancement weights
    let mut w_arr = vec![0.0f32; l + 1];
    for li in 1..=l {
        let temp = (PI_96 * (rm0sq + rm1sq - 2.0 * rm0 * rm1 * (params.w0 * li as f32).cos()))
            / (params.w0 * rm0 * (rm0sq - rm1sq));
        w_arr[li] = params.spectral[li].sqrt() * temp.powf(0.25);
    }

    // Alg #108
    let mut enhanced = vec![0.0f32; l + 1];
    for li in 1..=l {
        if (8 * li) <= l {
            enhanced[li] = params.spectral[li];
        } else if w_arr[li] > 1.2 {
            enhanced[li] = params.spectral[li] * 1.2;
        } else if w_arr[li] < 0.5 {
            enhanced[li] = params.spectral[li] * 0.5;
        } else {
            enhanced[li] = params.spectral[li] * w_arr[li];
        }
    }

    // Alg #109 - energy normalization
    let mut denom: f32 = 0.0;
    for li in 1..=l {
        denom += enhanced[li] * enhanced[li];
    }
    let y = (rm0 / denom).sqrt();

    // Alg #110
    for li in 1..=l {
        enhanced[li] *= y;
    }

    // Alg #111
    params.local_energy = (0.95 * prev_local_energy) + (0.05 * rm0);
    if params.local_energy < 10000.0 {
        params.local_energy = 10000.0;
    }

    params.enhanced_spectral = enhanced;
    apply_adaptive_smoothing(params, prev_amp_threshold);
}

fn apply_adaptive_smoothing(params: &mut ModelParameters, prev_amp_threshold: i32) {
    let l = params.l;

    // Alg #112
    let vm: f32;
    if params.error_rate <= 0.005 && params.error_count_total <= 4 {
        vm = f32::MAX;
    } else {
        let energy = params.local_energy.powf(0.375);
        if params.error_rate <= 0.0125 && params.error_count4 == 0 {
            vm = (45.255 * energy) / (277.26 * params.error_rate).exp();
        } else {
            vm = 1.414 * energy;
        }

        // Alg #113 - adaptive threshold on voicing decisions
        for li in 1..=l {
            if params.enhanced_spectral[li] > vm {
                params.voicing[li] = true;
            }
        }
    }

    // Alg #114
    let mut am: f32 = 0.0;
    for li in 1..=l {
        am += params.enhanced_spectral[li];
    }

    // Alg #115
    let tm: i32;
    if params.error_rate <= 0.005 && params.error_count_total <= 6 {
        tm = 20480;
    } else {
        tm = 6000 - (300 * params.error_count_total as i32) + prev_amp_threshold;
    }
    params.amplitude_threshold = tm;

    // Alg #116
    if am > tm as f32 {
        let scale = tm as f32 / am;
        for li in 1..=l {
            params.enhanced_spectral[li] *= scale;
        }
    }
}


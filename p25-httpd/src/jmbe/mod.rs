/// Compute w0 and L for a given index (0..=207).
/// w0 = 4 * PI / (index + 39.5)
/// L  = floor(0.9254 * floor(PI / w0 + 0.25))
fn compute_fundamental(index: u32) -> (f32, usize) {
    let w0 = 4.0 * PI / (index as f32 + 39.5);
    let l = (0.9254 * ((PI / w0) + 0.25).floor()).floor() as usize;
    (w0, l)
}

